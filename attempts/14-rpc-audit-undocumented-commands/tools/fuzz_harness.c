/*
 * GSP-RM RPC handler audit harness -- real implementation (was a skeleton).
 * See MANUAL.md in this directory for the full plan and safety discipline.
 *
 * Standalone: does NOT build or link against a separate internal reference
 * tool (that tool is scoped to a different machine/GPU with its own policy
 * docs, and its own safety policy forbids opening /dev/nvidia* there
 * without the maintainer's authorization). This reuses the same minimal,
 * already-hardware-proven
 * ioctl pattern as ../../bf16-unlock-blackwell-research/tools/register-access/
 * regops.c (freestanding struct defs, no NVIDIA headers needed for the ioctl
 * layer itself) -- that tool's RM_ALLOC/RM_CONTROL plumbing has already run
 * successfully on this exact machine's actual driver (595.99.02).
 *
 * command_sizes.tsv (gen/command_sizes.tsv, generated by gen/extract_pairs.py
 * + gen/sizeof_probe.c against the REAL 595.91.07 header tree, compiler-
 * verified sizeof()s, not hand-counted) supplies, per line:
 *   <CTRL_CMD name> <TAB> <hex cmd id> <TAB> <PARAMS struct name> <TAB> <documented size in bytes>
 *
 * Build:  gcc -O2 -Wall -Wextra -o fuzz_harness fuzz_harness.c
 * Usage:  sudo ./fuzz_harness <gpu_index> <bdf> list
 *         sudo ./fuzz_harness <gpu_index> <bdf> <cmd_hex> <documented_size>
 *
 * HARD SAFETY RULE, enforced in code, not just prose (MANUAL.md "Safety and
 * crash recovery"): this binary processes exactly ONE command per
 * invocation and, within that command, pauses for operator confirmation
 * (stdin) after EVERY individual attempt before sending the next variation.
 * There is no flag to disable this and no loop over the whole command list --
 * moving to the next command, or the next variation, is a human decision
 * made by running the program again / pressing Enter, never an automatic
 * one. This mirrors ../sr-resume/run_untested_fields.sh's own "one
 * experiment, confirm the box came back, then continue" pattern, adapted to
 * this job's different hazard (a corrupted-but-still-running GSP-RM rather
 * than a hung resume).
 */
#define _GNU_SOURCE
#include <errno.h>
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/ioctl.h>
#include <time.h>
#include <unistd.h>

#define NV_IOCTL_MAGIC    'F'
#define NV_ESC_RM_ALLOC   0x2B
#define NV_ESC_RM_CONTROL 0x2A
#define NV_ESC_REGISTER_FD (200 + 1)

#define NV01_ROOT_CLIENT 0x00000041u
#define NV01_DEVICE_0    0x00000080u
#define NV20_SUBDEVICE_0 0x00002080u

/* Deliberately generous: the whole point is to send sizes that deviate from
 * documented_size, including "longer than documented" variations. 8192 bytes
 * covers every entry in command_sizes.tsv with wide headroom (largest
 * observed documented size in this run was ~2KB) plus room to double it. */
#define MAX_PARAMS_BYTES 8192

typedef uint32_t NvHandle;
typedef uint64_t NvP64;

typedef struct {
    NvHandle hRoot, hObjectParent, hObjectNew;
    int32_t  hClass;
    NvP64    pAllocParms;
    uint32_t paramsSize;
    int32_t  status;
} nvos21_t;

typedef struct {
    NvHandle hClient, hObject;
    int32_t  cmd;
    uint32_t flags;
    NvP64    params;
    uint32_t paramsSize;
    int32_t  status;
} nvos54_t;

typedef struct {
    uint32_t deviceId;
    NvHandle hClientShare, hTargetClient, hTargetDevice;
    int32_t  flags;
    uint64_t vaSpaceSize, vaStartInternal, vaLimitInternal;
    int32_t  vaMode;
} nv0080_t;

typedef struct { uint32_t subDeviceId; } nv2080_t;

/* Opaque-enough handle bundle. The skeleton's comment said "fill in from
 * nvrm_open()'s actual return type once wired against that other tool" -- we
 * are deliberately not wired against it (see header comment), so this is the
 * standalone equivalent: the three handles regops.c's own alloc chain
 * already proved sufficient for RM_CONTROL calls on this hardware. */
typedef struct nvrm_client {
    int fd_ctl;
    int fd_dev;
    NvHandle client, device, subdevice;
} nvrm_client_t;

static int rm_alloc_raw(int fd, nvos21_t *p)
{
    return ioctl(fd, _IOC(_IOC_READ | _IOC_WRITE, NV_IOCTL_MAGIC,
                          NV_ESC_RM_ALLOC, sizeof(*p)), p);
}

static int alloc_obj(int fd, NvHandle root, NvHandle parent, uint32_t cls,
                      void *params, uint32_t psz, NvHandle *out, const char *label)
{
    nvos21_t p;
    memset(&p, 0, sizeof p);
    p.hRoot = root;
    p.hObjectParent = parent;
    p.hObjectNew = (cls == 0x41 /* NV01_ROOT_CLIENT */) ? 0 : 0xcaf00000u + cls;
    p.hClass = (int32_t)cls;
    p.pAllocParms = (NvP64)(uintptr_t)params;
    p.paramsSize = psz;
    if (rm_alloc_raw(fd, &p) != 0) {
        fprintf(stderr, "alloc %-10s ioctl errno=%d\n", label, errno);
        return -1;
    }
    if (p.status != 0) {
        fprintf(stderr, "alloc %-10s RM status=0x%x\n", label, (unsigned)p.status);
        return -1;
    }
    *out = p.hObjectNew;
    fprintf(stderr, "alloc %-10s -> handle 0x%x\n", label, *out);
    return 0;
}

/*
 * rm_control_raw() -- the one primitive the skeleton asked for. Sends
 * EXACTLY `size` bytes at `params` as the NVOS54_PARAMETERS payload for
 * control command `cmd`, with NO relationship enforced between `size` and
 * whatever the real documented struct size is. This is the opposite of a
 * normal rm_control(): a normal one always derives psz from sizeof(), which
 * is exactly what a fuzzer must not do.
 *
 * Returns the raw ioctl() return value (0 or -1/errno) via *ioctl_rc, and the
 * RM-level status word via *rm_status -- uninterpreted in both cases. The
 * caller (fuzz_one_command) decides what either value means for this cmd.
 */
static void rm_control_raw(nvrm_client_t *client, uint32_t cmd, void *params,
                            uint32_t size, int *ioctl_rc, int *ioctl_errno,
                            int32_t *rm_status)
{
    nvos54_t p;
    memset(&p, 0, sizeof p);
    p.hClient = client->client;
    p.hObject = client->subdevice;
    p.cmd = (int32_t)cmd;
    p.params = (NvP64)(uintptr_t)params;
    p.paramsSize = size;
    errno = 0;
    *ioctl_rc = ioctl(client->fd_ctl,
                      _IOC(_IOC_READ | _IOC_WRITE, NV_IOCTL_MAGIC,
                           NV_ESC_RM_CONTROL, sizeof(p)), &p);
    *ioctl_errno = errno;
    *rm_status = p.status;
}

/* Best-effort diagnostic shell-out: the exit code of the diagnostic itself
 * is not part of this harness's control flow (a failed `dmesg`/`nvidia-smi`
 * invocation is itself informative -- it's logged by virtue of producing no
 * output -- not a reason to abort), so the return value is intentionally
 * discarded through this named wrapper rather than silently at each call
 * site. */
static void run_diag(const char *cmd)
{
    if (system(cmd) == -1)
        fprintf(stderr, "    (diagnostic shell-out itself failed to start)\n");
}

static void dmesg_tail(const char *label)
{
    printf("  -- %s --\n", label);
    fflush(stdout);
    run_diag("dmesg -T 2>/dev/null | tail -8 | sed 's/^/    dmesg: /'");
}

static void nvidia_smi_probe(void)
{
    /* A quick liveness probe between attempts. Exit status / hang-ness of
     * this call itself is informative: if nvidia-smi hangs, the GPU/driver
     * is in worse shape than a clean ioctl error would indicate. */
    printf("  -- nvidia-smi -L (liveness probe, 10s timeout) --\n");
    fflush(stdout);
    run_diag("timeout -s KILL 10 nvidia-smi -L 2>&1 | sed 's/^/    smi: /'");
}

static int confirm_continue(const char *prompt)
{
    char line[64];
    printf("%s [Enter=continue, Ctrl-C=stop] ", prompt);
    fflush(stdout);
    if (!fgets(line, sizeof line, stdin))
        return 0; /* EOF/closed stdin: treat as stop, never as implicit yes */
    return 1;
}

/*
 * One fuzz iteration against a single command ID, per MANUAL.md's workflow:
 *   1. send the documented-correct size once (sanity baseline)
 *   2. send a small, named set of size/content variations
 *   3. STOP AND ASSESS after every single attempt, not just at the end --
 *      the operator confirms the box/GPU still looks fine before the next
 *      one is even constructed, let alone sent.
 *
 * This function does not loop blindly and cannot be made to without editing
 * it: confirm_continue() is called between every attempt, with no bypass.
 */
static int fuzz_one_command(nvrm_client_t *client, uint32_t cmd, uint32_t documented_size)
{
    static uint8_t buf[MAX_PARAMS_BYTES];
    int ioctl_rc, ioctl_errno;
    int32_t rm_status;

    struct { const char *name; uint32_t size; int fill_pattern; } variants[] = {
        { "documented size (baseline)", documented_size, 0 },
        { "zero-length",                0,                0 },
        { "size - 1 (if >0)",           documented_size > 0 ? documented_size - 1 : 0, 0 },
        { "size + 1",                   documented_size + 1, 0 },
        { "size * 2",                   documented_size * 2 > MAX_PARAMS_BYTES ? MAX_PARAMS_BYTES : documented_size * 2, 0 },
        { "documented size, 0xFF fill", documented_size, 1 },
        { "documented size, last word 0xFFFFFFFF", documented_size, 2 },
    };
    size_t nvariants = sizeof(variants) / sizeof(variants[0]);

    printf("=== command 0x%08x, documented_size=%u ===\n", cmd, documented_size);
    printf("Per MANUAL.md: read this handler's actual GSP-RM code BEFORE this "
           "point (cross_repo_findings.md Sec7 for extraction). This harness "
           "does not do that for you.\n");

    for (size_t i = 0; i < nvariants; i++) {
        uint32_t size = variants[i].size;
        if (size > MAX_PARAMS_BYTES) {
            printf("[%zu/%zu] %-42s SKIPPED (size %u exceeds MAX_PARAMS_BYTES=%u)\n",
                   i + 1, nvariants, variants[i].name, size, MAX_PARAMS_BYTES);
            continue;
        }

        memset(buf, 0, sizeof buf);
        if (variants[i].fill_pattern == 1 && size > 0)
            memset(buf, 0xFF, size);
        if (variants[i].fill_pattern == 2 && size >= 4)
            memset(buf + size - 4, 0xFF, 4);

        printf("[%zu/%zu] %-42s size=%u -> sending...\n",
               i + 1, nvariants, variants[i].name, size);
        fflush(stdout);

        rm_control_raw(client, cmd, buf, size, &ioctl_rc, &ioctl_errno, &rm_status);

        printf("    ioctl_rc=%d errno=%d(%s) rm_status=0x%x\n",
               ioctl_rc, ioctl_errno, ioctl_rc != 0 ? strerror(ioctl_errno) : "-",
               (unsigned)rm_status);

        dmesg_tail("post-attempt dmesg");
        nvidia_smi_probe();

        printf("    >>> Look at the dmesg/smi output above. Anything that "
               "looks like an Xid, a hang in nvidia-smi, a crash, or an "
               "unexpected SUCCESS deserves stopping here, not continuing.\n");
        if (!confirm_continue("    Continue to the next variation for THIS command?")) {
            printf("Stopped by operator (or closed stdin) after variation %zu/%zu.\n",
                   i + 1, nvariants);
            return 0;
        }
    }

    printf("=== command 0x%08x: all %zu variations attempted, no stop requested ===\n",
           cmd, nvariants);
    printf("Per MANUAL.md step 5: understand this command's behavior across "
           "these inputs before moving to a different command -- do not just "
           "conclude 'didn't crash this time.'\n");
    return 0;
}

static void usage(const char *argv0)
{
    fprintf(stderr,
        "usage: sudo %s <gpu_index> <bdf> list\n"
        "       sudo %s <gpu_index> <bdf> <cmd_hex> <documented_size>\n"
        "\n"
        "  list                    print every (cmd, size) pair this binary\n"
        "                          knows about, from gen/command_sizes.tsv\n"
        "                          embedded at build time -- does not open\n"
        "                          /dev/nvidia*.\n"
        "  <cmd_hex> <size>        run fuzz_one_command() against exactly\n"
        "                          ONE command. There is deliberately no way\n"
        "                          to pass a whole file and have this binary\n"
        "                          iterate it unattended -- see MANUAL.md and\n"
        "                          the header comment in this file.\n",
        argv0, argv0);
}

int main(int argc, char **argv)
{
    if (argc < 4) {
        usage(argv[0]);
        return 2;
    }

    int gpu = atoi(argv[1]);
    const char *bdf = argv[2]; (void)bdf; /* kept for CLI symmetry with regops.c */

    if (strcmp(argv[3], "list") == 0) {
        printf("This build does not embed the TSV; read gen/command_sizes.tsv directly:\n");
        printf("  wc -l gen/command_sizes.tsv ; column -t -s $'\\t' gen/command_sizes.tsv | less\n");
        return 0;
    }

    if (argc < 5) {
        usage(argv[0]);
        return 2;
    }
    uint32_t cmd = (uint32_t)strtoul(argv[3], NULL, 16);
    uint32_t documented_size = (uint32_t)strtoul(argv[4], NULL, 0);

    if ((size_t)geteuid() != 0) {
        fprintf(stderr, "must run as root\n");
        return 1;
    }

    nvrm_client_t client;
    memset(&client, 0, sizeof client);

    client.fd_ctl = open("/dev/nvidiactl", O_RDWR);
    if (client.fd_ctl < 0) {
        fprintf(stderr, "open /dev/nvidiactl: %s\n", strerror(errno));
        return 1;
    }

    if (alloc_obj(client.fd_ctl, 0, 0, NV01_ROOT_CLIENT, NULL, 0, &client.client, "client") < 0)
        return 1;

    nv0080_t dev_parms;
    memset(&dev_parms, 0, sizeof dev_parms);
    dev_parms.deviceId = (uint32_t)gpu;
    if (alloc_obj(client.fd_ctl, client.client, client.client, NV01_DEVICE_0,
                  &dev_parms, sizeof dev_parms, &client.device, "device") < 0) {
        char devpath[32];
        snprintf(devpath, sizeof devpath, "/dev/nvidia%d", gpu);
        client.fd_dev = open(devpath, O_RDWR);
        if (client.fd_dev >= 0) {
            int ctl_fd = client.fd_ctl;
            printf("retrying after NV_ESC_REGISTER_FD on %s\n", devpath);
            ioctl(client.fd_dev, _IOC(_IOC_READ | _IOC_WRITE, NV_IOCTL_MAGIC,
                                      NV_ESC_REGISTER_FD, sizeof(int)), &ctl_fd);
            if (alloc_obj(client.fd_ctl, client.client, client.client, NV01_DEVICE_0,
                          &dev_parms, sizeof dev_parms, &client.device, "device") < 0)
                return 1;
        } else {
            return 1;
        }
    }

    nv2080_t sub_parms = { .subDeviceId = 0 };
    if (alloc_obj(client.fd_ctl, client.client, client.device, NV20_SUBDEVICE_0,
                  &sub_parms, sizeof sub_parms, &client.subdevice, "subdevice") < 0)
        return 1;

    printf("RM client/device/subdevice allocated: client=0x%x device=0x%x subdevice=0x%x\n",
           client.client, client.device, client.subdevice);
    printf("About to fuzz ONE command (0x%08x, documented_size=%u). ", cmd, documented_size);
    if (!confirm_continue("Proceed?")) {
        printf("Stopped before first attempt.\n");
        return 0;
    }

    return fuzz_one_command(&client, cmd, documented_size);
}
